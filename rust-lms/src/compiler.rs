pub struct Compiler {
    /// Function definitions indexed by ID
    functions: Vec<Option<FunDef>>,
    /// External function definitions indexed by ID
    extern_functions: Vec<ExternFnDef>,
    /// Next variable ID to assign
    next_var_id: usize,
    /// Code-generation backend `compile` targets.
    backend: JitBackend,
    /// Keep each function's Cranelift IR as readable text; see [`DEBUG_IR_SOURCE`].
    debug_ir_source: bool,
    /// Whether [`DEBUG_IR_SOURCE`] was set when this compiler was made.
    debug_ir_source_env: bool,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum JitBackend {
    Cranelift,
    #[cfg(feature = "llvm")]
    Llvm,
}

#[derive(Debug)]
pub enum CompileError {
    JitError(String),
    ModuleError(String),
}

impl std::fmt::Display for CompileError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            CompileError::JitError(msg) => write!(f, "JIT error: {}", msg),
            CompileError::ModuleError(msg) => write!(f, "Module error: {}", msg),
        }
    }
}

impl std::error::Error for CompileError {}

impl Default for Compiler {
    fn default() -> Self {
        Self::new()
    }
}

