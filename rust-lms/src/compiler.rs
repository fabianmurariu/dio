    /// Keep each function's Cranelift IR as readable text (builder style), as
    /// [`DEBUG_IR_SOURCE`] does, without the environment. Cranelift only. Set it before
    /// defining functions: their statements record their origins as they are defined.
    pub fn with_debug_ir_source(mut self, on: bool) -> Self {
        self.debug_ir_source = on;
        self
    }

    /// Whether to keep readable text: the builder flag or [`DEBUG_IR_SOURCE`], read once
    /// in [`new`](Self::new) so that it costs nothing per function or instruction.
    fn debug_ir_source(&self) -> bool {
        self.debug_ir_source || self.debug_ir_source_env
    }

    /// Register an external function and get a handle to call it.
    ///
    /// The type parameter `S` must be a type generated by the `#[extern_fn]` macro,
    /// which implements the `ExternFn` trait with all necessary metadata.
    ///
    /// # Example
    ///
    /// ```ignore
    /// use rust_lms_derive::extern_fn;
    ///
    /// #[extern_fn]
    /// #[no_mangle]
    /// pub extern "C" fn my_add(x: i64, y: i64) -> i64 {
    ///     x + y
    /// }
    ///
    /// let mut compiler = Compiler::new();
    /// let my_add = compiler.extern_fn::<MyAddExtern>();
    /// let result = call_extern2(my_add, x, y);
    /// ```
    pub fn extern_fn<S: ExternFn>(&mut self) -> crate::ffi::ExternRef<S> {
        let extern_id = self.extern_functions.len();

        self.extern_functions.push(ExternFnDef {
            // Disambiguate generic instantiations (same NAME, different fn ptr).
            name: format!("{}_{:x}", S::NAME, S::FN_PTR as usize),
            num_params: S::NUM_PARAMS,
            fn_ptr: S::FN_PTR,
        });

        crate::ffi::ExternRef::new(extern_id)
    }

    /// Define a unary function.
